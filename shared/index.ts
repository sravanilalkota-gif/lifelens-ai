/**
 * LifeLens AI — shared domain types & constants.
 * Used by BOTH the Express API and the React client (npm workspace package).
 *
 * The single most important contract in the app: `AnalysisResult`.
 * LifeLens never returns "just OCR text" — it returns structured,
 * actionable understanding of what the camera saw.
 */

export type Priority = 'HIGH' | 'MEDIUM' | 'LOW';

export type Category =
  | 'Academic'
  | 'Assignment'
  | 'Event'
  | 'Finance'
  | 'Health'
  | 'Personal'
  | 'Travel'
  | 'Other';

