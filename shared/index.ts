/** How the capture was understood. Surfaced in the UI so the demo is honest. */
export type AiMode = 'gemini' | 'demo';

/** Everything the AI extracted + decided about one capture. */
export interface AnalysisResult {
  title: string;
  description: string | null;
  category: Category;
  subject: string | null;
  /** ISO date only: YYYY-MM-DD. null when the document has no date. */
  date: string | null;
  /** 24h HH:mm. null when not stated. */
  time: string | null;
  location: string | null;
  priority: Priority;
  /** 0..1 model confidence in the extraction as a whole. */
  confidence: number;
  /** The single most useful next action, in the user's voice. */
  action: string | null;
  /** ISO date (YYYY-MM-DD) on which to remind the user. */
  reminder: string | null;
  /** Concrete checklist items LifeLens derived from the capture. */
  tasks: string[];
  /** Plain-language reasoning, e.g. "High priority because the exam is within 2 days." */
  priorityReason: string | null;
  /** Fields the model was unsure about → the UI marks them editable/uncertain. */
  uncertainFields: string[];
  /** Raw text the model read (OCR-ish), kept for transparency + search. */
  sourceText: string | null;
  aiMode: AiMode;
  /** Only in demo mode: which sample document matched. */
  demoKey?: string;
  note?: string;
}

export interface Capture {
  id: string;
  userId: string;
  /** data:image/...;base64,... (kept so the demo works with zero external storage) */
  imageData?: string | null;
  imageName?: string | null;
  createdAt: string;
  result: AnalysisResult;
  /** true once the user confirmed "Add to my tasks". */
  saved: boolean;
  /** user edited fields after AI analysis (trust layer) */
  edited?: boolean;
}

export interface Task {
  id: string;
  userId: string;
  captureId?: string | null;
  title: string;
  category: Category;
  subject?: string | null;
  priority: Priority;
  priorityReason?: string | null;
  /** ISO date only. */
  dueDate?: string | null;
  /** HH:mm */
  dueTime?: string | null;
  location?: string | null;
  reminder?: string | null;
  action?: string | null;
  description?: string | null;
  done: boolean;
  createdAt: string;
  /** Sub-steps generated by LifeLens. */
  subtasks: Subtask[];
}

export interface Subtask {
  id: string;
  title: string;
  done: boolean;
}

