export function priorityRank(p: Priority): number {
  return p === 'HIGH' ? 3 : p === 'MEDIUM' ? 2 : 1;
}

/** YYYY-MM-DD in local time (never UTC — deadlines are a human concept). */
export function localDateKey(d: Date = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function addDaysKey(baseKey: string, days: number): string {
  const d = new Date(`${baseKey}T00:00:00`);
  d.setDate(d.getDate() + days);
  return localDateKey(d);
}

/** Whole-day difference (today = 0, tomorrow = 1, yesterday = -1). null if no date. */
export function daysUntil(dateKey: string | null | undefined, from: Date = new Date()): number | null {
  if (!dateKey) return null;
  const target = new Date(`${dateKey}T00:00:00`);
  if (Number.isNaN(target.getTime())) return null;
  const a = new Date(from.getFullYear(), from.getMonth(), from.getDate()).getTime();
  const b = new Date(target.getFullYear(), target.getMonth(), target.getDate()).getTime();
  return Math.round((b - a) / 86400000);
}

export function relativeDueLabel(dateKey: string | null | undefined): string {
  const d = daysUntil(dateKey);
  if (d === null) return 'No date';
  if (d < 0) return d === -1 ? 'Yesterday' : `${Math.abs(d)} days overdue`;
  if (d === 0) return 'Today';
  if (d === 1) return 'Tomorrow';
  if (d < 7) return `in ${d} days`;
  const weeks = Math.round(d / 7);
  return `in ${weeks} week${weeks === 1 ? '' : 's'}`;
}
